#!/usr/bin/env python
"""
Build mdd_processing with Nuitka (compiled, obfuscated package).
Produces a pip-installable wheel (.whl) in dist/.
"""
import hashlib
import re
import shutil
import subprocess
import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parent.parent
CONFIG_FILE = PROJECT_ROOT / "mdd_processing.nuitka-package.config.yml"
OUTPUT_DIR = PROJECT_ROOT / "dist"
MODULE_NAME = "mdd_processing"
DATA_CONFIGS = PROJECT_ROOT / MODULE_NAME / "preprocessing" / "Data" / "data_configs"


def copy_data_files():
    """Copy YAML configs to dist (required at runtime; Nuitka module mode does not bundle them)."""
    dest = OUTPUT_DIR / "preprocessing" / "Data" / "data_configs"
    dest.mkdir(parents=True, exist_ok=True)
    for f in DATA_CONFIGS.glob("*.yaml"):
        shutil.copy2(f, dest / f.name)
    print(f"Copied {len(list(DATA_CONFIGS.glob('*.yaml')))} YAML configs to {dest}")


LOADER_INIT_PY = r'''# Loader for Nuitka-built .pyd (do not edit; generated by build_nuitka.py)
import importlib.util
import glob
import os

_here = os.path.dirname(os.path.abspath(__file__))
_pyd_candidates = glob.glob(os.path.join(_here, "mdd_processing*.pyd"))

if _pyd_candidates:
    _ext_path = _pyd_candidates[0]
    _spec = importlib.util.spec_from_file_location("mdd_processing", _ext_path)
    _mod = importlib.util.module_from_spec(_spec)
    _spec.loader.exec_module(_mod)
    for _name in dir(_mod):
        if not _name.startswith("_"):
            globals()[_name] = getattr(_mod, _name)
    __all__ = getattr(_mod, "__all__", ["run_preprocessing", "preprocessing"])
else:
    raise ImportError("mdd_processing*.pyd not found next to this __init__.py")
'''


def add_init_and_rename_pyd():
    """Same layout as before: dist/mdd_processing/ with .pyd and preprocessing/. Add __init__.py and rename .pyd to mdd_processing.pyd (no .cp310... suffix)."""
    pkg_dir = OUTPUT_DIR / MODULE_NAME
    pkg_dir.mkdir(parents=True, exist_ok=True)

    # Move .pyd into package dir and rename to mdd_processing.pyd
    for pyd in OUTPUT_DIR.glob("mdd_processing*.pyd"):
        shutil.move(str(pyd), str(pkg_dir / "mdd_processing.pyd"))
        print(f"Placed {pyd.name} as mdd_processing.pyd in {pkg_dir}")
        break

    # Move .pyi into package dir (Nuitka writes it next to the .pyd in dist/)
    for pyi in OUTPUT_DIR.glob("mdd_processing*.pyi"):
        shutil.move(str(pyi), str(pkg_dir / "mdd_processing.pyi"))
        print(f"Placed {pyi.name} as mdd_processing.pyi in {pkg_dir}")
        break

    # Move preprocessing/ into package dir
    prep = OUTPUT_DIR / "preprocessing"
    if prep.exists():
        dest_prep = pkg_dir / "preprocessing"
        if dest_prep.exists():
            shutil.rmtree(dest_prep)
        shutil.move(str(prep), str(dest_prep))
        print(f"Moved preprocessing/ into {pkg_dir}")

    (pkg_dir / "__init__.py").write_text(LOADER_INIT_PY, encoding="utf-8")
    print(f"Wrote {pkg_dir / '__init__.py'}")


def _get_version():
    """Read version from pyproject.toml."""
    text = (PROJECT_ROOT / "pyproject.toml").read_text(encoding="utf-8")
    m = re.search(r'version\s*=\s*"([^"]+)"', text)
    return m.group(1) if m else "0.0.0"


def _hash_file(path: Path) -> str:
    """Return SHA256 hash of file in RECORD format (base64url)."""
    import base64
    h = hashlib.sha256()
    with open(path, "rb") as f:
        h.update(f.read())
    return base64.urlsafe_b64encode(h.digest()).decode("ascii").rstrip("=")


def create_wheel():
    """Create a pip-installable wheel from the Nuitka-built package."""
    import platform
    version = _get_version()
    pkg_dir = OUTPUT_DIR / MODULE_NAME
    if not pkg_dir.exists():
        print("Package dir not found, skipping wheel creation")
        return

    # Platform tag: Windows binary extension
    impl = f"py{sys.version_info.major}{sys.version_info.minor}"
    plat = "win_amd64" if platform.system() == "Windows" else "manylinux2014_x86_64"
    tag = f"{impl}-none-{plat}"

    wheel_name = f"{MODULE_NAME}-{version}-{tag}.whl"
    dist_info = f"{MODULE_NAME}-{version}.dist-info"

    # Build unpacked wheel in a temp dir
    import tempfile
    with tempfile.TemporaryDirectory() as tmp:
        root = Path(tmp)
        dest_pkg = root / MODULE_NAME
        shutil.copytree(pkg_dir, dest_pkg)
        (root / dist_info).mkdir()

        # METADATA (minimal PKG-INFO)
        metadata = f"""Metadata-Version: 2.1
Name: {MODULE_NAME}
Version: {version}
Requires-Python: >=3.10
"""
        (root / dist_info / "METADATA").write_text(metadata, encoding="utf-8")

        # WHEEL
        wheel_content = f"""Wheel-Version: 1.0
Generator: build_nuitka.py
Root-Is-Pure-Lib: false
Tag: {tag}
"""
        (root / dist_info / "WHEEL").write_text(wheel_content, encoding="utf-8")

        # RECORD: collect all files with hashes
        record_lines = []
        for f in sorted(root.rglob("*")):
            if f.is_file():
                rel = f.relative_to(root)
                rel_str = str(rel).replace("\\", "/")
                size = f.stat().st_size
                digest = _hash_file(f)
                record_lines.append(f"{rel_str},sha256={digest},{size}")

        record_lines.append(f"{dist_info}/RECORD,,")
        (root / dist_info / "RECORD").write_text("\n".join(record_lines) + "\n", encoding="utf-8")

        # Create wheel (zip with .whl extension)
        whl_path = OUTPUT_DIR / wheel_name
        import zipfile
        with zipfile.ZipFile(whl_path, "w", zipfile.ZIP_DEFLATED) as zf:
            for f in root.rglob("*"):
                if f.is_file():
                    arcname = f.relative_to(root)
                    zf.write(f, arcname)

        print(f"\nCreated pip-installable wheel: {whl_path}")
        print(f"  pip install {whl_path.name}")
        print(f"  pip install s3://.../{wheel_name}  (after download)")
    return wheel_name


def main():
    cmd = [
        sys.executable,
        "-m",
        "nuitka",
        "--module",
        f"--output-dir={OUTPUT_DIR}",
        f"--include-package={MODULE_NAME}",
        f"--user-package-configuration-file={CONFIG_FILE}",
        "--remove-output",  # Clean build cache after
        "--assume-yes-for-downloads",
        MODULE_NAME,
    ]
    print("Running:", " ".join(cmd))
    result = subprocess.run(cmd, cwd=PROJECT_ROOT)
    if result.returncode != 0:
        sys.exit(result.returncode)
    copy_data_files()
    add_init_and_rename_pyd()
    create_wheel()
    print(f"\nBuild complete. Package directory: {OUTPUT_DIR / MODULE_NAME}")
    print("\nDeps in target env: pip install numpy pandas scipy PyYAML geographiclib geopy AHRS typing_extensions")


if __name__ == "__main__":
    main()
